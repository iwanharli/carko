export function petaDasar(el, opsi = {}) {
  const map = L.map(el, opsi);
  L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', { maxZoom: 19, attribution: '© OpenStreetMap' }).addTo(map);
  return map;
}
export const pin = (cls, ikon) => L.divIcon({ className: '', html: `<div class="pin ${cls}">${SVG[ikon]}</div>`, iconSize: [36, 36], iconAnchor: [18, 36] });
export { L };
